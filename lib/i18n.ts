export const MESSAGES: Record<Lang, Messages> = { tr, en };

export type ErrorCode = keyof Messages["errors"];

export function isLang(value: unknown): value is Lang {
  return value === "tr" || value === "en";
}

export function errorText(t: Messages, code: unknown): string {
  return typeof code === "string" && code in t.errors ? t.errors[code as ErrorCode] : t.errors.generic;
}
